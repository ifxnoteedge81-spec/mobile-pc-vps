@Composable
fun PermissionsAndSecurityScreen(
    accessibilityConnected: Boolean,
    accessibilityHealth: com.example.accessibility.AccessibilityHealthState =
        if (accessibilityConnected) com.example.accessibility.AccessibilityHealthState.CONNECTED
        else com.example.accessibility.AccessibilityHealthState.DISABLED,
    backgroundKeepAliveEnabled: Boolean = true,
    daemonRunning: Boolean = false,
    batteryUnrestricted: Boolean = false,
    waNotificationBound: Boolean = false,
    networkEvents: List<NetworkEvent>,
    onOpenAccessibilitySettings: () -> Unit,
    onToggleBackgroundKeepAlive: (Boolean) -> Unit = {},
    onOpenBatterySettings: () -> Unit = {},
    onOpenAppInfoSettings: () -> Unit = {},
    onOpenNotificationSettings: () -> Unit = {},
    onClearAllData: () -> Unit
) {
    val context = LocalContext.current
    var showWipeConfirm by remember { mutableStateOf(false) }

    val notifGranted = if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.TIRAMISU) {
        ContextCompat.checkSelfPermission(context, Manifest.permission.POST_NOTIFICATIONS) == PackageManager.PERMISSION_GRANTED
    } else true

    val micGranted = ContextCompat.checkSelfPermission(context, Manifest.permission.RECORD_AUDIO) == PackageManager.PERMISSION_GRANTED

    val notifLauncher = rememberLauncherForActivityResult(ActivityResultContracts.RequestPermission()) {}
    val micLauncher = rememberLauncherForActivityResult(ActivityResultContracts.RequestPermission()) {}

    LazyColumn(
        modifier = Modifier
            .fillMaxSize()
            .testTag("permissions_security_screen"),
        contentPadding = PaddingValues(16.dp),
        verticalArrangement = Arrangement.spacedBy(12.dp)
    ) {
        item {
            SectionHeader(
                title = "Permissions, Privacy & Security",
                subtitle = "Zero hidden servers. Local-first data & Android Keystore encryption.",
                icon = Icons.Filled.Security
            )
        }

        item {
            GlassOsCard(borderColor = if (daemonRunning && batteryUnrestricted) EmeraldPulse.copy(alpha = 0.55f) else AmberWarning.copy(alpha = 0.65f)) {
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    horizontalArrangement = Arrangement.SpaceBetween,
                    verticalAlignment = Alignment.CenterVertically
                ) {
                    Text("24/7 Background Engine & OEM Shield", style = MaterialTheme.typography.titleSmall)
                    StatusBadge(
                        label = if (daemonRunning) "DAEMON ACTIVE" else "IDLE",
                        color = if (daemonRunning) EmeraldPulse else AmberWarning
                    )
                }
                Spacer(Modifier.height(6.dp))
                SwitchRow("Always-On Background Keep-Alive", backgroundKeepAliveEnabled, onToggleBackgroundKeepAlive)
                Spacer(Modifier.height(6.dp))
                PermissionActionRow(
                    title = "Battery Optimization (Unrestricted)",
                    status = if (batteryUnrestricted) "Unrestricted (Safe from Killing)" else "Optimized (Phone may kill in background)",
                    isOk = batteryUnrestricted,
                    actionLabel = "Battery",
                    onAction = onOpenBatterySettings
                )
                Spacer(Modifier.height(8.dp))
                PermissionActionRow(
                    title = "Android 13–15 Restricted Settings Unlock",
                    status = "যদি Accessibility বা Notification সুইচ গ্রে/লক থাকে, App Info → উপরের ডানে ⋮ → Allow restricted settings দিন",
                    isOk = accessibilityConnected && waNotificationBound,
                    actionLabel = "App Info",
                    onAction = onOpenAppInfoSettings
                )
            }
        }

        item {
            GlassOsCard {
                Text("System Permissions", style = MaterialTheme.typography.titleSmall)
                Spacer(Modifier.height(8.dp))
                PermissionActionRow(
                    title = "Accessibility Virtual Hands",
                    status = when (accessibilityHealth) {
                        com.example.accessibility.AccessibilityHealthState.CONNECTED -> "Connected & Live"
                        com.example.accessibility.AccessibilityHealthState.ENABLED_BUT_UNBOUND -> "Enabled in Settings but Unbound — toggle OFF then ON"
                        com.example.accessibility.AccessibilityHealthState.DISABLED -> "Disabled"
                    },
                    isOk = accessibilityConnected,
                    actionLabel = "Settings",
                    onAction = onOpenAccessibilitySettings
                )
                Spacer(Modifier.height(8.dp))
                PermissionActionRow(
                    title = "WhatsApp Notification Listener",
                    status = if (waNotificationBound) "Bound & Listening" else "Unbound / Disabled",
                    isOk = waNotificationBound,
                    actionLabel = "Open",
                    onAction = onOpenNotificationSettings
                )
                Spacer(Modifier.height(8.dp))
                PermissionActionRow(
                    title = "Notifications (Scheduled Tasks)",
                    status = if (notifGranted) "Granted" else "Optional",
                    isOk = notifGranted,
                    actionLabel = "Grant",
                    onAction = {
                        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.TIRAMISU) {
                            notifLauncher.launch(Manifest.permission.POST_NOTIFICATIONS)
                        }
                    }
                )
                Spacer(Modifier.height(8.dp))
                PermissionActionRow(
                    title = "Microphone (Voice Input)",
                    status = if (micGranted) "Granted" else "On Demand",
                    isOk = micGranted,
                    actionLabel = "Grant",
                    onAction = { micLauncher.launch(Manifest.permission.RECORD_AUDIO) }
                )
            }
        }

        item {
            GlassOsCard {
                Text("3-Tier Permission Policy", style = MaterialTheme.typography.titleSmall)
                Spacer(Modifier.height(6.dp))
                PermissionLevel.entries.forEach { lvl ->
                    Text("${lvl.title}: ${lvl.description}", style = MaterialTheme.typography.bodySmall)
                    Spacer(Modifier.height(4.dp))
                }
            }
        }

        item {
            GlassOsCard(borderColor = CoralAlert.copy(alpha = 0.6f)) {
                Text("Data Control & Secure Wipe", style = MaterialTheme.typography.titleSmall, color = CoralAlert)
                Spacer(Modifier.height(4.dp))
                Text(
                    "Erase all task history, agent memory, audit logs, and encrypted API keys from this device.",
                    style = MaterialTheme.typography.bodySmall
                )
                Spacer(Modifier.height(8.dp))
                Button(
                    onClick = { showWipeConfirm = true },
                    colors = ButtonDefaults.buttonColors(containerColor = CoralAlert)
                ) {
                    Icon(Icons.Filled.DeleteForever, contentDescription = null, modifier = Modifier.size(18.dp))
                    Spacer(Modifier.width(6.dp))
                    Text("Wipe Local Vault & History")
                }
            }
        }

        item {
            Text("Outbound Network Visibility (${networkEvents.size})", style = MaterialTheme.typography.titleSmall)
        }
        if (networkEvents.isEmpty()) {
            item {
                GlassOsCard {
                    Text(
                        "No outbound network requests recorded in this session.",
                        style = MaterialTheme.typography.bodySmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant
                    )
                }
            }
        } else {
            items(networkEvents.take(20), key = { it.id }) { ev ->
                GlassOsCard {
                    Row(
                        modifier = Modifier.fillMaxWidth(),
                        horizontalArrangement = Arrangement.SpaceBetween
                    ) {
                        Text(ev.destination, style = MaterialTheme.typography.titleSmall)
                        StatusBadge(label = ev.status, color = NeuralCyan)
                    }
                    Text("${ev.purpose} • ${formatBytes(ev.bytesTransferred)}", style = MaterialTheme.typography.bodySmall)
                }
            }
        }
    }

    if (showWipeConfirm) {
        AlertDialog(
            onDismissRequest = { showWipeConfirm = false },
            title = { Text("Wipe All Local Data?") },
            text = { Text("This deletes all encrypted API keys, agent memory, and task logs immediately.") },
            confirmButton = {
                Button(onClick = { onClearAllData(); showWipeConfirm = false }) { Text("Confirm Wipe") }
            },
            dismissButton = { TextButton(onClick = { showWipeConfirm = false }) { Text("Cancel") } }
        )
    }
}

